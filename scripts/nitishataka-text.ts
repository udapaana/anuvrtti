#!/usr/bin/env bun
/**
 * nitishataka-text.ts — cut the Nītiśataka out of the combined Śatakatraya
 * (Ambuda's GRETIL fork, TEI: data/sources/sa_bhatRhari-zatakatraya.xml,
 * pinned in data/texts.json) and write content/texts/nitishataka/text.yaml in
 * the standard whole-text format (see content/texts/pancatantra-kilotpatin/text.yaml).
 *
 * The śataka is the TEI's first <div> (n="1", headed nīti-śatakam), not a
 * verse count. Each verse closes with `|| N ||`; N becomes the section id —
 * the number the reader's 18_nitishataka excerpts cite (bharst_1.N).
 *
 * The mass conversion that made the TEI misplaces two kinds of verse, and this
 * mends both rather than guess past them:
 *   - a verse typed without its half-verse daṇḍa (8, 14, 46, 48) has its first
 *     pāda in a <p> before the <lg>: that unnumbered line is the verse's first;
 *   - verse 66 is a <p> of its own, numbered: a verse all the same.
 *
 * A verse's lines are its pādas; the single daṇḍa marks the half. `lines`
 * holds the two halves in Devanagari saṃhitā (iastToDeva: analytic spacing
 * rejoined, compound hyphens dropped) and `iast` the pādas exactly, halves
 * joined by " | ". The script fails on a gap in the numbering or a verse
 * without exactly two halves.
 *
 *   bun scripts/nitishataka-text.ts
 */
import * as fs from 'fs';
import * as path from 'path';
import { createRequire } from 'module';
import { iastToDeva } from './analyze-text';
import { readTei } from './lib/tei';

const require = createRequire(import.meta.url);
const { initSync, transliterate } = require('shlesha');
initSync({ module: fs.readFileSync(require.resolve('shlesha/shlesha_bg.wasm')) });

const ROOT = process.cwd();
const SLUG = 'sa_bhatRhari-zatakatraya';
const OUT = path.join(ROOT, 'content/texts/nitishataka/text.yaml');

type Verse = { n: number; padas: string[] };
const verses: Verse[] = [];
let lead: string[] = [];
for (const b of readTei(SLUG).filter((x) => x.div[0] === '1')) {
  if (b.kind === 'head') continue;
  if (!b.ref) { lead.push(...b.lines); continue; } // a first pāda, set adrift
  verses.push({ n: Number(b.ref), padas: [...lead, ...b.lines] });
  lead = [];
}
if (lead.length) { console.error(`lines with no verse number: ${lead.join(' / ')}`); process.exit(1); }

const problems: string[] = [];
verses.forEach((v, i) => { if (v.n !== i + 1) problems.push(`verse ${i + 1}: numbered ${v.n}`); });

// Four verses (8, 14, 46, 48) are typed without the half-verse daṇḍa. Each has
// four pādas on four lines, so the half falls after the second; the script
// supplies it and the header names them.
const supplied: number[] = [];
const norm = (x: string) => x.replace(/\s+/g, ' ').trim();
const sections = verses.map((v) => {
  // Halves as lists of pādas. GRETIL applies no sandhi across a pāda break, so
  // each pāda is rejoined on its own: dhārayet | na tu must not become धारयेत्न.
  let halves: string[][] = [[]];
  for (const line of v.padas) {
    const parts = line.split('|');
    parts.forEach((p, i) => {
      if (i > 0) halves.push([]);
      if (norm(p)) halves[halves.length - 1].push(norm(p));
    });
  }
  halves = halves.filter((h) => h.length);
  if (halves.length === 1 && v.padas.length === 4) {
    halves = [v.padas.slice(0, 2), v.padas.slice(2)].map((h) => h.map(norm));
    supplied.push(v.n);
  }
  if (halves.length !== 2) problems.push(`bharst_1.${v.n}: ${halves.length} halves`);
  return {
    id: String(v.n),
    lines: halves.map((h) => h.map(iastToDeva).join(' ')),
    iast: halves.map((h) => h.join(' ')).join(' | '),
  };
});
// A GRETIL typo that Devanagari cannot spell (avaokate, naivaa: two vowels
// in hiatus) comes out of the transliterator quietly changed. Name each one,
// so the Devanagari is not taken for GRETIL's exact typing.
const bare = (x: string) => x.replace(/[\s'|-]/g, '').replace(/ṁ/g, 'ṃ');
const respelled = sections
  .filter((s) => bare(transliterate(s.lines.join(' '), 'devanagari', 'iast')) !== bare(s.iast))
  .map((s) => s.id);
// a bare YAML scalar must not hold ': ' or ' #'
for (const s of sections) for (const l of s.lines) if (/: | #/.test(l)) problems.push(`${s.id}: line needs quoting: ${l}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const esc = (s: string) => JSON.stringify(s);
const y: string[] = [
  '# Bhartṛhari, Nītiśataka, whole — the first of the Śatakatraya.',
  '#',
  '# AUTHORED SOURCE of a whole text: generated by scripts/nitishataka-text.ts from',
  "# the combined Śatakatraya (Ambuda's GRETIL fork, TEI), its first division.",
  '# Re-run the script to regenerate; corrections to vidyut\'s analysis belong in',
  '# overrides.yaml. See content/texts/pancatantra-kilotpatin/text.yaml for the format.',
  '#',
  '# `lines` is Devanagari saṃhitā, one line to a half-verse; `iast` is GRETIL\'s',
  '# pādas exactly, its compound hyphens kept for audit. Section ids are the',
  '# edition\'s verse numbers (bharst_1.N), the same the reader cites: never',
  '# renumber one. Verse 1 is the maṅgala. The reader excerpts these as a',
  '# word-by-word chapter (18_nitishataka).',
  '#',
  `# GRETIL types ${supplied.length} verses (${supplied.join(', ')}) without the half-verse daṇḍa;`,
  '# the script supplies it after the second pāda, in `iast` as well as `lines`.',
  ...(respelled.length ? [
    `# In ${respelled.join(', ')} GRETIL types two vowels in hiatus, a typo Devanagari cannot`,
    '# spell, so `lines` differs from `iast` there; each is noted in the overrides.',
  ] : []),
  'id: nitishataka',
  'title: नीतिशतकम्',
  'title_en: Bhartṛhari’s Nītiśataka',
  'work: नीतिशतकम्',
  `place: the whole śataka, verses 1–${sections.length}`,
  'source:',
  '  edition: Nītiśataka, ed. Śrīkṛṣṇamaṇi Tripāṭhī (Chaukhamba Vidya Bhavan, 1990), input by J. K. Brzezinski, via GRETIL and Ambuda',
  '  file: sa_bhatRhari-zatakatraya # data/texts.json (sha256-pinned; Ambuda\'s GRETIL fork)',
  '  ref: TEI <div n="1"> (nīti-śatakam), verses 1–109',
  '  licence: GRETIL text, CC BY-NC-SA 4.0 (per its header)',
  'sections:',
];
for (const s of sections) {
  y.push(`  - id: '${s.id}'`, '    kind: verse', '    lines:');
  for (const l of s.lines) y.push(`      - ${l}`);
  y.push(`    iast: ${esc(s.iast)}`);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, y.join('\n') + '\n');
console.log(`wrote ${path.relative(ROOT, OUT)}: ${sections.length} verses, ${sections.reduce((n, s) => n + s.lines.join(' ').split(/\s+/).length, 0)} words`);
