#!/usr/bin/env bun
/**
 * condensed-text.ts — turn a condensed book's selection (scripts/condensed.ts)
 * into a whole text: content/texts/<work>-condensed/text.yaml, in the standard
 * format (see content/texts/pancatantra-kilotpatin/text.yaml).
 *
 *   bun scripts/condensed-text.ts ramayana
 *
 * Each placed entry becomes a section holding its verse as the edition gives it
 * — the book contributes the choice and the order, never the words. Entries
 * the selection could not place (unmatched, or found only in another
 * recension) are left out and counted in the header.
 *
 * Section ids are kāṇḍa.sarga.verse, from the edition id: R_1.001.001 → 1.1.1
 * (the Baroda critical edition, Ambuda's GRETIL text). A verse the book quotes
 * twice gets "#2". Parts are the kāṇḍas.
 */
import * as fs from 'fs';
import * as path from 'path';
import { readTei } from './lib/tei';
import { iastToDeva } from './analyze-text';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const { initSync, transliterate } = require('shlesha');
initSync({ module: fs.readFileSync(require.resolve('shlesha/shlesha_bg.wasm')) });

const ROOT = process.cwd();
const work = process.argv[2];
if (work !== 'ramayana') { console.error('usage: bun scripts/condensed-text.ts ramayana'); process.exit(1); }

const DIR = path.join(ROOT, 'content/texts/ramayana-condensed');
const sel = JSON.parse(fs.readFileSync(path.join(DIR, 'selection.json'), 'utf-8'));
// verses the edition lacks, read from the book's scan and settled by double keying
// (condensed-reocr.ts → transcribe-*.json → condensed-keyed.ts)
const keyedFile = path.join(DIR, 'keyed.json');
const keyed = new Map<number, { section: string; text: string; by: string }>(
  fs.existsSync(keyedFile) ? JSON.parse(fs.readFileSync(keyedFile, 'utf-8')).map((k: any) => [k.ocr_line, k]) : []);

// the editions' verses, by id: lines of IAST, daṇḍas and running heads dropped
const verses = new Map<string, string[]>();
const tidy = (l: string) => l.replace(/[|/।॥]+/g, ' ').replace(/\s+/g, ' ').trim();
for (const b of readTei('sa_rAmAyaNa')) if (b.kind === 'verse' && b.id) verses.set(b.id, b.lines.map(tidy).filter(Boolean));

const sectionId = (eid: string) => {
  let m = eid.match(/^R_(\d)\.(\d+)\.(\d+)$/);
  if (m) return `${+m[1]}.${+m[2]}.${+m[3]}`;
  throw new Error(`unexpected edition id ${eid}`);
};
const KANDA = ['', 'बालकाण्डम्', 'अयोध्याकाण्डम्', 'अरण्यकाण्डम्', 'किष्किन्धाकाण्डम्', 'सुन्दरकाण्डम्', 'युद्धकाण्डम्', 'उत्तरकाण्डम्'];

type Sec = { id: string; lines: string[]; iast: string; eid: string; scan?: string };
const sections: Sec[] = [];
const seen = new Map<string, number>();
const left = { unmatched: 0, elsewhere: 0, missing: 0 };
let fromScan = 0;
for (const e of sel.entries) {
  if (!e.edition_id) {
    const k = keyed.get(e.ocr_line);
    if (k) {
      const lines = k.text.split(' / ').map((l) => l.trim()).filter(Boolean);
      sections.push({ id: k.section, lines, iast: lines.map((l) => transliterate(l, 'devanagari', 'iast')).join(' | '), eid: '', scan: k.by });
      fromScan++;
      continue;
    }
    if (e.elsewhere || e.critical) left.elsewhere++; else left.unmatched++;
    continue;
  }
  const v = verses.get(e.edition_id);
  if (!v?.length) { left.missing++; console.error(`no verse text for ${e.edition_id}`); continue; }
  const base = sectionId(e.edition_id);
  const n = (seen.get(base) ?? 0) + 1;
  seen.set(base, n);
  // a verse the book quotes twice in a row (half, then the rest) is one section
  if (n > 1 && sections.at(-1)?.eid === e.edition_id) continue;
  sections.push({ id: n > 1 ? `${base}#${n}` : base, lines: v.map(iastToDeva), iast: v.join(' | '), eid: e.edition_id });
}
if (left.missing) process.exit(1);

// parts: one per kāṇḍa, in the order the book walks them
const parts: { id: string; title: string; first: string; last: string }[] = [];
for (const s of sections) {
  const k = s.id.split('.')[0];
  if (parts.at(-1)?.id === k) parts.at(-1)!.last = s.id;
  else parts.push({ id: k, title: KANDA[+k], first: s.id, last: s.id });
}

const esc = (s: string) => JSON.stringify(s);
const words = sections.reduce((n, s) => n + s.lines.join(' ').split(/\s+/).length, 0);
const y: string[] = [
  '# The Rāmāyaṇa, condensed — the verse selection of P. P. S. Sastri\'s book.',
  '#',
  '# AUTHORED SOURCE of a whole text: generated by scripts/condensed-text.ts from',
  '# selection.json (itself generated by scripts/condensed.ts, with the human',
  '# reviews in review-*.json). Re-run the script to regenerate; corrections to the',
  '# selection belong in a review file, to vidyut\'s analysis in overrides.',
  '#',
  '# Every verse is the edition\'s, not the book\'s OCR: the Baroda critical edition',
  '# (Ambuda\'s GRETIL text). `lines` is Devanagari saṃhitā, a line to a half-verse;',
  '# `iast` the edition\'s lines exactly. The book follows the Southern/vulgate',
  '# text; a Kumbhakonam edition to supply its other verses is still owed.',
  '#',
  `# ${fromScan} verses the critical edition lacks (the book follows the vulgate) come from`,
  '# the book itself: cut from its scan, transcribed twice independently, every',
  '# difference settled by a third reading (keyed.json; crops in',
  '# data/sources/ocr/ramayana-condensed-crops/). Their ids are the critical verse',
  '# the book quotes before them, plus +n; each carries `scan:`. A Kumbhakonam',
  '# text is to replace them (content/texts/TODO.md).',
  '#',
  `# Left out: ${left.unmatched} entries the matcher could not place, and ${left.elsewhere} vulgate`,
  '# verses not yet settled from the scan.',
  'id: ramayana-condensed',
  'title: रामायणम् (संक्षिप्तम्)',
  'title_en: "The Rāmāyaṇa, condensed in the poet\'s own words"',
  'work: रामायणम्',
  `place: ${sections.length} verses chosen by P. P. S. Sastri (1935), Bāla to Yuddha, in order`,
  'source:',
  '  edition: "Vālmīki, Rāmāyaṇa: the Baroda critical edition via GRETIL and Ambuda. Selection from P. P. S. Sastri, Valmiki Ramayana Condensed in the Poet\'s Own Words (G. A. Natesan, Madras, 1935)"',
  '  file: sa_rAmAyaNa # data/texts.json (sha256-pinned)',
  '  ref: by section id, kāṇḍa.sarga.verse',
  '  licence: GRETIL text, CC BY-NC-SA 4.0 (per its header)',
  'parts:',
  ...parts.flatMap((p) => [`  - id: '${p.id}'`, `    title: ${p.title}`, `    first: '${p.first}'`, `    last: '${p.last}'`]),
  'sections:'
];
for (const s of sections) {
  y.push(`  - id: '${s.id}'`, '    kind: verse', ...(s.scan ? [`    scan: ${s.scan} # read from the book's scan, double-keyed`] : []), '    lines:');
  for (const l of s.lines) y.push(`      - ${JSON.stringify(l)}`);
  y.push(`    iast: ${esc(s.iast)}`);
}
fs.writeFileSync(path.join(DIR, 'text.yaml'), y.join('\n') + '\n');
console.log(`wrote content/texts/ramayana-condensed/text.yaml: ${sections.length} verses (${fromScan} from the scan), ${words} words, ${parts.length} parts; left out ${left.unmatched} unmatched, ${left.elsewhere} vulgate verses not yet settled`);
