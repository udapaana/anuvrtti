#!/usr/bin/env bun
/**
 * condensed.ts — the Rāmāyaṇa and Bhāgavata volumes of the G. A. Natesan
 * "Condensed in the Poet's Own Words" series, matched into their full texts
 * the way scripts/mbh-condensed.ts matches the Mahābhārata
 * (scripts/lib/condensed-match.ts does the matching).
 *
 *   bun scripts/condensed.ts ramayana             → content/texts/ramayana-condensed/selection.json
 *   bun scripts/condensed.ts bhagavata            → content/texts/bhagavata-condensed/selection.json
 *   bun scripts/condensed.ts ramayana --k2 critical   (Ayodhyā from the critical text, to compare)
 *   … --sample 20                                 print N matches to check by eye
 *   bun scripts/condensed.ts ramayana --find "<Devanagari line>"   the closest edition lines, with ids
 *                                                 (for reviewing an unmatched entry by hand)
 *
 * The editions, all committed under data/sources/ (data/texts.json):
 *   Rāmāyaṇa  Ambuda's GRETIL text (the Baroda critical edition), except the
 *             Ayodhyākāṇḍa, which is T. R. Krishnacharya's Southern recension
 *             (Kumbhakonam, 1905) — the only kāṇḍa of it in digital form. The
 *             1935 book follows the Southern text; where it quotes a verse the
 *             critical edition omits, in another kāṇḍa, the verse stays
 *             unmatched rather than be forced onto a neighbour.
 *   Bhāgavata Ambuda's GRETIL text (data entry Ulrich Stiehl).
 * Both are IAST; the OCR is Devanagari, so the edition is transliterated.
 */
import * as fs from 'fs';
import * as path from 'path';
import { createRequire } from 'module';
import { readTei, type Block } from './lib/tei';
import { matchCondensed, skel, sim } from './lib/condensed-match';

const require = createRequire(import.meta.url);
const { initSync, transliterate } = require('shlesha');
initSync({ module: fs.readFileSync(require.resolve('shlesha/shlesha_bg.wasm')) });
const deva = (s: string) => transliterate(s, 'iast', 'devanagari') as string;

const ROOT = process.cwd();
const args = process.argv.slice(2);
const work = args[0];
const opt = (k: string) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/texts.json'), 'utf-8'));
const ocr = (id: string) => fs.readFileSync(path.join(ROOT, manifest.ocr.find((o: { id: string }) => o.id === id).file), 'utf-8');

type Line = { id: string; text: string };
const linesOf = (blocks: Block[], idOf: (b: Block) => string | undefined, clean = (s: string) => s): Line[] => {
  const out: Line[] = [];
  for (const b of blocks) {
    if (b.kind !== 'verse') continue;
    const id = idOf(b);
    if (!id) continue;
    let prev = '';
    for (const raw of b.lines) {
      const t = clean(raw).replace(/[|/।॥]+/g, ' ').replace(/\s+/g, ' ').trim();
      if (!t || t === prev) continue; // the Bhāgavata repeats a long line once
      prev = t;
      out.push({ id, text: deva(t) });
    }
  }
  return out;
};

const KANDA = ['', 'bala', 'ayodhya', 'aranya', 'kishkindha', 'sundara', 'yuddha', 'uttara'];

/** --find: the edition lines nearest a (damaged) OCR line, by the matcher's own measure. */
function find(lines: Line[], q: string) {
  const k = skel(q);
  const top = lines.map((l) => ({ l, s: sim(k, skel(l.text)) })).sort((a, b) => b.s - a.s).slice(0, 8);
  for (const t of top) console.log(`${t.s.toFixed(2)}  ${t.l.id}  ${t.l.text}`);
}
const FIND = opt('--find');

if (work === 'ramayana') {
  const k2 = opt('--k2') ?? 'southern';
  const crit = readTei('sa_rAmAyaNa');
  const critLines = linesOf(crit, (b) => b.id); // R_1.001.001
  const kOf = (id: string) => Number(id.match(/^R(?:amS)?_(\d)/)?.[1] ?? 0);
  // Krishnacharya's Ayodhyā: ids from the closing marker (RamS_2,1.1); the
  // first line of each sarga is a running head ("Rāmāyaṇa, Ayodhyākāṇḍa, 1")
  const south = linesOf(readTei('sa_vAlmIki-rAmAyaNa-southern-2'), (b) => b.ref, (s) => (/^Rāmāyaṇa,/.test(s) ? '' : s));
  const lines = k2 === 'critical' ? critLines : [
    ...critLines.filter((l) => kOf(l.id) === 1),
    ...south,
    ...critLines.filter((l) => kOf(l.id) >= 3)
  ];
  if (FIND) { find(args.includes('--all') ? [...lines, ...critLines.filter((l) => kOf(l.id) === 2)] : lines, FIND); process.exit(0); }
  matchCondensed({
    ocrText: ocr('ramayana-condensed'), lines, group: (id) => KANDA[kOf(id)] ?? '?',
    idField: 'edition_id', groupField: 'kanda',
    outDir: path.join(ROOT, k2 === 'critical' ? 'content/texts/ramayana-condensed/compare-k2-critical' : 'content/texts/ramayana-condensed'),
    join: args.includes('--join'), sample: Number(opt('--sample')) || 0,
    note: 'Generated by scripts/condensed.ts ramayana. edition_id: R_k.sss.vvv is the Baroda critical edition (Ambuda\'s GRETIL text); RamS_2,s.v is T. R. Krishnacharya\'s Southern Ayodhyākāṇḍa (Kumbhakonam, 1905). band: high ≥ .75 skeleton similarity; medium ≥ .55; low = weaker, or placed only by its neighbours (placed_by: context); unmatched = OCR verse text with no place found.'
  });
} else if (work === 'bhagavata') {
  const lines = linesOf(readTei('sa_bhAgavatapurANa'), (b) => b.ref?.replace(/\*$/, ''), (s) => s.replace(/[$&%]/g, ' '));
  if (FIND) { find(lines, FIND); process.exit(0); }
  matchCondensed({
    ocrText: ocr('bhagavata-condensed'), lines, group: (id) => `skandha-${Number(id.slice(4, 6))}`,
    idField: 'edition_id', groupField: 'skandha',
    outDir: path.join(ROOT, 'content/texts/bhagavata-condensed'),
    join: args.includes('--join'), sample: Number(opt('--sample')) || 0,
    note: 'Generated by scripts/condensed.ts bhagavata. edition_id: BhP_ss.aa.vvv in Ambuda\'s GRETIL text (data entry Ulrich Stiehl). band: high ≥ .75 skeleton similarity; medium ≥ .55; low = weaker, or placed only by its neighbours (placed_by: context); unmatched = OCR verse text with no place found.'
  });
} else {
  console.error('usage: bun scripts/condensed.ts ramayana|bhagavata [--k2 critical] [--sample N]');
  process.exit(1);
}
